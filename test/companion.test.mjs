import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright-core';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const pause=ms=>new Promise(r=>setTimeout(r,ms));

test('companion isolates origins, leases an action once, and displays discovered settings',async t=>{
  const temp=await fs.mkdtemp(path.join(os.tmpdir(),'flow-companion-test-'));
  const port=4318,base='http://127.0.0.1:'+port;
  const child=spawn(process.execPath,[path.join(root,'src','server.mjs'),'--no-open'],{env:{...process.env,FLOW_PROTO_PORT:String(port),FLOW_PROTO_STATE_DIR:temp},stdio:'pipe',windowsHide:true});
  let logs='';child.stderr.on('data',d=>logs+=d);
  t.after(async()=>{child.kill();await new Promise(r=>{if(child.exitCode!==null)r();else child.once('close',r);});if(path.dirname(temp)!==path.resolve(os.tmpdir())||!path.basename(temp).startsWith('flow-companion-test-'))throw new Error('Unexpected test cleanup path.');await fs.rm(temp,{recursive:true,force:true});});
  let control;
  for(let attempt=0;attempt<600;attempt++){try{control=JSON.parse(await fs.readFile(path.join(temp,'control.json'),'utf8'));break;}catch{if(child.exitCode!==null)throw new Error(logs||'Companion did not start.');await pause(50);}}
  assert(control,logs||'Companion startup exceeded 30 seconds.');
  const uiHeaders={Authorization:'Bearer '+control.token,'Content-Type':'application/json'};
  const api=async(endpoint,data)=>{const response=await fetch(base+endpoint,{method:data===undefined?'GET':'POST',headers:uiHeaders,body:data===undefined?undefined:JSON.stringify(data)});assert(response.ok,await response.clone().text());return response.json();};
  assert.equal((await fetch(base+'/api/state')).status,401);
  assert.equal((await fetch(base+'/api/state',{headers:{...uiHeaders,Origin:'https://hostile.example'}})).status,403);
  const state=await api('/api/state');
  const extensionOrigin='chrome-extension://'+'a'.repeat(32);
  const pair=await fetch(base+'/bridge/pair',{method:'POST',headers:{Origin:extensionOrigin,'Content-Type':'application/json'},body:JSON.stringify({code:state.pairCode})});
  assert(pair.ok);const {token}=await pair.json();
  const bridgeRequest=async(endpoint,data)=>{const res=await fetch(base+endpoint,{method:'POST',headers:{Origin:extensionOrigin,'Content-Type':'application/json',Authorization:'Bearer '+token},body:JSON.stringify(data)});assert(res.ok,await res.clone().text());return res.json();};
  const bridge=data=>bridgeRequest('/bridge/poll',{tabId:5,...data});
  const fixturePage='https://flow.google.com/project/fixture';
  await bridge({snapshot:{version:'0.1.3',controls:[],images:[],dialogs:[],tiles:[{mediaIds:['fixture-asset']}],page:fixturePage}});
  const responsePromise=api('/api/command',{type:'inspect'});await pause(80);
  const first=await bridge({});assert.equal(first.command.type,'inspect');
  const second=await bridge({});assert.equal(second.command,null,'A disconnected action is never redelivered');
  await bridge({results:[{id:first.command.id,result:{controls:[],ok:true}}]});assert((await responsePromise).ok);
  await api('/api/capabilities',{models:['Fixture model'],ratios:['1:1','16:9'],counts:[1,2],resolutions:['1K','2K'],resolutionOptions:[{value:'1K',label:'1K · Original',enabled:true},{value:'2K',label:'2K · Upscaled',enabled:true},{value:'4K',label:'4K · Upgrade required',enabled:false}],defaults:{model:'Fixture model',ratio:'1:1',count:1,resolution:'2K'}});
  const output=path.join(temp,'output');await api('/api/settings',{outputFolder:output});
  await api('/api/download-existing',{page:fixturePage,mediaId:'fixture-asset',prompt:'Fixture token',resolution:'2K'});await pause(80);
  const downloadCommand=(await bridge({})).command;assert.equal(downloadCommand.type,'download');
  const marker=downloadCommand.payload.marker,started=Date.now();
  await bridgeRequest('/bridge/arm',{marker,started,title:'Fixture token',page:fixturePage+'/edit/asset',resolution:'2K',sourceOrigin:'https://images.example'});
  const decision=await bridgeRequest('/bridge/candidate',{marker,item:{filename:'Fixture_token_2K_20261021220000.png',startTime:new Date(started+1).toISOString(),mime:'image/png',referrerOrigin:'https://flow.google.com',sourceOrigin:'https://images.example'}});
  assert.equal(decision.match,true);
  const source=path.join(temp,marker+'.png');await fs.writeFile(source,Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aCzkAAAAASUVORK5CYII=','base64'));
  await bridgeRequest('/bridge/download',{marker,filename:source});
  await bridge({results:[{id:downloadCommand.id,result:{started:true}}]});await pause(40);
  const returnCommand=(await bridge({})).command;assert.equal(returnCommand.type,'returnToProject');
  await bridge({results:[{id:returnCommand.id,result:{ok:true}}]});await pause(40);
  const finished=await api('/api/state');assert.equal(finished.queue.status,'complete');assert.equal(finished.queue.items[0].files.length,1);
  assert(await fs.stat(path.join(output,marker+'.png')));
  await api('/api/settings',{defaults:{count:2,autoCrop:false},draft:'Saved fixture draft'});
  const preferences=(await api('/api/state')).settings;
  assert.equal(preferences.defaults.count,2);assert.equal(preferences.defaults.autoCrop,false);
  assert.equal(JSON.parse(await fs.readFile(path.join(temp,'settings.json'),'utf8')).draft,'Saved fixture draft');
  const history=await api('/api/history');assert.equal(history.items.length,1);assert.equal(history.items[0].count,1);
  await api('/api/history/select',{id:history.items[0].id});assert.equal((await api('/api/state')).queue.items[0].prompt,'Fixture token');
  await api('/api/desktop/heartbeat',{});assert.equal((await api('/api/state')).desktopOpen,true);
  await api('/api/desktop/heartbeat',{closed:true});assert.equal((await api('/api/state')).desktopOpen,false);
  await bridgeRequest('/bridge/select-tab',{tabId:7,page:fixturePage});
  const staleTab=await fetch(base+'/bridge/poll',{method:'POST',headers:{Origin:extensionOrigin,'Content-Type':'application/json',Authorization:'Bearer '+token},body:JSON.stringify({tabId:5})});assert.equal(staleTab.status,409);
  await bridge({tabId:7,snapshot:{version:'0.1.4',controls:[],images:[],dialogs:[],tiles:[],page:fixturePage}});
  assert.equal((await api('/api/state')).paired,true);
  const candidates=[process.env.PROGRAMFILES,process.env['PROGRAMFILES(X86)'],process.env.LOCALAPPDATA].filter(Boolean).map(folder=>path.join(folder,'Google','Chrome','Application','chrome.exe'));
  let executablePath;for(const file of candidates){try{await fs.access(file);executablePath=file;break;}catch{}}
  assert(executablePath,'Chrome must be available for the dashboard test.');
  const browser=await chromium.launch({executablePath,headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1366,height:900}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'/#key='+control.token);
    await page.getByText('Flow connected',{exact:true}).waitFor();
    assert.equal(await page.locator('#model').inputValue(),'Fixture model');
    assert.equal(await page.locator('#model').isEnabled(),true);
    assert.equal(await page.locator('#ratio option').count(),2);
    assert.equal(await page.locator('#resolution').inputValue(),'2K');assert.equal(await page.locator('#resolution option[value="4K"]').evaluate(option=>option.disabled),true);
    assert.equal(await page.locator('#setup').isVisible(),false);
    assert.equal(await page.locator('#prompts').inputValue(),'Saved fixture draft');
    await page.locator('#workspace-settings').click();await page.locator('[data-settings-tab="processing"]').click();
    assert.equal(await page.locator('#auto-crop').isChecked(),false);
    await page.locator('[data-close="workspace-settings-dialog"]').last().click();
    await page.locator('#prompts').fill('A local fixture prompt');await page.locator('#ratio').selectOption('16:9');
    assert.equal(await page.locator('#ratio').inputValue(),'16:9');
    assert.deepEqual(errors,[]);
    const diagnostics=path.join(root,'.local','diagnostics');await fs.mkdir(diagnostics,{recursive:true});
    await page.screenshot({path:path.join(diagnostics,'dashboard.png'),fullPage:true});
    await page.setViewportSize({width:730,height:900});await page.screenshot({path:path.join(diagnostics,'dashboard-compact.png'),fullPage:true});
    assert.equal(await page.locator('body').evaluate(el=>el.scrollWidth<=innerWidth),true);
  }finally{await browser.close();}
  await api('/api/reset-pairing',{});const reset=await api('/api/state');assert.equal(reset.paired,false);assert(reset.pairCode);
  const revoked=await fetch(base+'/bridge/poll',{method:'POST',headers:{Origin:extensionOrigin,'Content-Type':'application/json',Authorization:'Bearer '+token},body:JSON.stringify({tabId:7})});assert.equal(revoked.status,401);
});
